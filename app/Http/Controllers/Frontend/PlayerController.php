<?php

namespace App\Http\Controllers\Frontend;

use App\Enums\RegistrationStatus;
use App\Http\Controllers\Controller;
use App\Http\Requests\Frontend\StorePlayerRequest;
use App\Mail\RegistrationReceived;
use App\Models\InternationalPlayer;
use App\Models\Player;
use App\Models\RegistrationDocument;
use App\Models\StateAssociation;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Mail;
use Illuminate\Support\Facades\Storage;
use Illuminate\View\View;
use Throwable;

class PlayerController extends Controller
{
    /**
     * The public Player Database: approved players only, and only their
     * name, Player ID and state association (CLAUDE.md section 14, Privacy).
     */
    public function index(Request $request): View
    {
        $search = trim((string) $request->query('q'));
        $associationId = $request->integer('association');

        return view('frontend.players.index', [
            'players' => Player::query()
                ->select(['id', 'registration_no', 'name', 'state_association_id'])
                ->where('status', RegistrationStatus::Approved)
                ->when($search !== '', fn (Builder $query) => $query->where(fn (Builder $query) => $query
                    ->where('name', 'like', '%'.$search.'%')
                    ->orWhere('registration_no', 'like', '%'.$search.'%')))
                ->when($associationId > 0, fn (Builder $query) => $query->where('state_association_id', $associationId))
                ->with('stateAssociation:id,name')
                ->orderBy('name')
                ->orderBy('id')
                ->paginate(25)
                ->withQueryString(),
            'associations' => StateAssociation::query()->approved()->orderBy('name')->get(['id', 'name']),
        ]);
    }

    /**
     * Players register under an approved association; while none exists the
     * view shows a short message instead of the form.
     */
    public function create(): View
    {
        return view('frontend.players.register', [
            'associations' => StateAssociation::query()->approved()->orderBy('name')->get(['id', 'name', 'state']),
        ]);
    }

    /**
     * Save the registration as pending (the Player ID is generated by the
     * model), with the photo and documents on the private disk, then send
     * the confirmation email. Files are removed again if the database insert
     * fails; a mail failure is only reported.
     */
    public function store(StorePlayerRequest $request): RedirectResponse
    {
        $photo = $request->file('photo')?->store('player-photos', 'local');
        $documents = RegistrationDocument::storeUploads($request->file('documents'), 'registration-documents/players');

        try {
            $player = DB::transaction(function () use ($request, $photo, $documents): Player {
                $player = Player::create([
                    ...$request->safe()->only([
                        'name', 'father_name', 'date_of_birth', 'gender', 'email', 'phone', 'password',
                        'address', 'city', 'state', 'pincode', 'state_association_id',
                    ]),
                    'photo' => $photo,
                    'terms_accepted_at' => now(),
                ]);

                $player->documents()->createMany($documents);

                return $player;
            });
        } catch (Throwable $exception) {
            Storage::disk('local')->delete(array_filter([$photo, ...array_column($documents, 'file_path')]));

            throw $exception;
        }

        try {
            Mail::to($player->email)->send(new RegistrationReceived($player));
        } catch (Throwable $exception) {
            report($exception);
        }

        return redirect()
            ->route('frontend.players.register')
            ->with('registered_player', ['name' => $player->name, 'registration_no' => $player->registration_no]);
    }

    public function international(): View
    {
        return view('frontend.players.international', [
            'internationalPlayers' => InternationalPlayer::query()
                ->published()
                ->orderBy('country')
                ->orderBy('sort_order')
                ->orderBy('name')
                ->get(),
        ]);
    }
}
